/**
 * AUTHORITATIVE CENTRAL SCHEMA — the single source of truth for what the
 * central PostgreSQL database must contain.
 *
 * This file is hand-maintained. It is intentionally NOT derived at runtime
 * from the local till schema: the till carries local-only bookkeeping
 * columns (is_synced, sync_status, last_error_at, …) and local-only tables
 * (sync_state, system_settings, transfers, shift_notifications) that must
 * never be demanded of the central database.
 *
 * Bump CENTRAL_SCHEMA_VERSION whenever this definition changes. It is
 * independent of the app version and the local database version.
 *
 * Column classification:
 *   required — the central database must have it; drift if absent.
 *   optional — used by some flows; reported but never blocks.
 *   legacy   — kept for historical data; never repaired, never dropped.
 */
export const CENTRAL_SCHEMA_VERSION = 1;

export type CentralColumnClass = "required" | "optional" | "legacy";

export type CentralColumnSpec = {
  name: string;
  /** PostgreSQL type, or a full additive fragment ("text not null default ''"). */
  pgType: string;
  classification?: CentralColumnClass;
};

export type CentralIndexSpec = {
  name: string;
  /** Full idempotent CREATE INDEX statement. */
  sql: string;
  /** Only emitted when one of these columns had to be repaired. */
  dependsOnColumns: string[];
  /** When true the index is expected to exist at all times, not only after a repair. */
  always?: boolean;
};

/** A constraint the central database must carry (unique / check / foreign key). */
export type CentralConstraintSpec = {
  name: string;
  /** Body only — "unique (a, b)" or "check (qty >= 0)" or "foreign key ...". */
  definition: string;
};

/** A row-security policy the central database must carry. */
export type CentralPolicySpec = {
  name: string;
  /** Full idempotent CREATE POLICY statement. */
  sql: string;
};

/** A trigger the central database must carry. */
export type CentralTriggerSpec = {
  name: string;
  /** Full idempotent CREATE TRIGGER statement. */
  sql: string;
};

export type CentralTableSchema = {
  table: string;
  label: string;
  primaryKey: string;
  columns: CentralColumnSpec[];
  indexes?: CentralIndexSpec[];
  constraints?: CentralConstraintSpec[];
  triggers?: CentralTriggerSpec[];
  policies?: CentralPolicySpec[];
  /**
   * Whether row-level security must be enabled. Central tables hold business
   * data reachable through the Data API, so the default is yes.
   */
  rowSecurity?: boolean;
};


